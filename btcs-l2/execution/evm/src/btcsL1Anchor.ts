import { ProtocolError } from './blockProcessor.js'

export const BTCS_L1_ANCHOR_FORMAT = 'btcs-l2-l1-anchor'
export const BTCS_L1_ANCHOR_VERSION = 1
export const BTCS_L1_ANCHOR_MAGIC_HEX = '425443534c32'

const HASH_RE = /^[0-9a-f]{64}$/
const PAYLOAD_HEX_LENGTH = 78
const OP_RETURN_PREFIX = '6a27'

export type BtcsL1AnchorPayload = Readonly<{
  format: typeof BTCS_L1_ANCHOR_FORMAT
  version: typeof BTCS_L1_ANCHOR_VERSION
  batchHash: string
}>

/**
 * Encode the OP_RETURN data field for a verified settlement batch.
 * The returned hex is unprefixed, as expected by Bitcoin-style Core RPCs.
 */
export function encodeBtcsL1AnchorPayload(batchHash: string): string {
  if (!HASH_RE.test(batchHash)) {
    throw new ProtocolError('batch hash must be 64 lowercase hex characters')
  }

  // BTCSL2 (6 bytes) + version 1 (1 byte) + SHA-256 hash (32 bytes).
  return `${BTCS_L1_ANCHOR_MAGIC_HEX}01${batchHash}`
}

/**
 * Decode and strictly validate the unprefixed OP_RETURN data payload.
 */
export function decodeBtcsL1AnchorPayload(
  payloadHex: string,
): BtcsL1AnchorPayload {
  if (
    typeof payloadHex !== 'string' ||
    payloadHex.length !== PAYLOAD_HEX_LENGTH ||
    !/^[0-9a-f]+$/.test(payloadHex)
  ) {
    throw new ProtocolError('BTCS L1 anchor payload is malformed')
  }

  if (!payloadHex.startsWith(BTCS_L1_ANCHOR_MAGIC_HEX)) {
    throw new ProtocolError('BTCS L1 anchor protocol marker does not match')
  }

  const versionHex = payloadHex.slice(BTCS_L1_ANCHOR_MAGIC_HEX.length,
    BTCS_L1_ANCHOR_MAGIC_HEX.length + 2)
  if (versionHex !== '01') {
    throw new ProtocolError('unsupported BTCS L1 anchor version')
  }

  return {
    format: BTCS_L1_ANCHOR_FORMAT,
    version: BTCS_L1_ANCHOR_VERSION,
    batchHash: payloadHex.slice(BTCS_L1_ANCHOR_MAGIC_HEX.length + 2),
  }
}

/**
 * Return the canonical scriptPubKey hex for one OP_RETURN data output.
 * Core's `createrawtransaction` data output should construct this script.
 */
export function encodeBtcsL1AnchorScript(batchHash: string): string {
  return `${OP_RETURN_PREFIX}${encodeBtcsL1AnchorPayload(batchHash)}`
}

/**
 * Parse only the canonical OP_RETURN script generated by this protocol.
 * This checks script contents, not transaction inclusion or confirmations.
 */
export function decodeBtcsL1AnchorScript(
  scriptPubKeyHex: string,
): BtcsL1AnchorPayload {
  if (
    typeof scriptPubKeyHex !== 'string' ||
    !scriptPubKeyHex.startsWith(OP_RETURN_PREFIX) ||
    scriptPubKeyHex.length !== OP_RETURN_PREFIX.length + PAYLOAD_HEX_LENGTH ||
    !/^[0-9a-f]+$/.test(scriptPubKeyHex)
  ) {
    throw new ProtocolError('scriptPubKey is not a canonical BTCS L1 anchor')
  }

  return decodeBtcsL1AnchorPayload(
    scriptPubKeyHex.slice(OP_RETURN_PREFIX.length),
  )
}
